function fillPolys(g, polys, project, style) {
  g.fillStyle = style;
  for (const poly of polys) {
    g.beginPath();
    poly.forEach(([lon, lat], i) => {
      const [x, y] = project(lon, lat);
      if (i === 0) g.moveTo(x, y);
      else g.lineTo(x, y);
    });
    g.closePath();
    g.fill();
  }
}

function strokePolys(g, polys, project, style, width, closed = true) {
  g.strokeStyle = style;
  g.lineWidth = width;
  g.lineJoin = 'round';
  g.lineCap = 'round';
  for (const poly of polys) {
    g.beginPath();
    poly.forEach(([lon, lat], i) => {
      const [x, y] = project(lon, lat);
      if (i === 0) g.moveTo(x, y);
      else g.lineTo(x, y);
    });
    if (closed) g.closePath();
    g.stroke();
  }
}

function paint(g, w, h, project, theme) {
  g.fillStyle = theme.sea;
  g.fillRect(0, 0, w, h);
  const land = [AFROEURASIA, ...ISLANDS, ...AMERICAS_AND_REST];
  strokePolys(g, land, project, theme.shallow, theme.shallowWidth);
  fillPolys(g, land, project, theme.land);
  fillPolys(g, INNER_SEAS, project, theme.sea);
  strokePolys(g, [...land, ...INNER_SEAS], project, theme.coast, theme.coastWidth);
  if (theme.river) strokePolys(g, RIVERS, project, theme.river, theme.riverWidth, false);

  // Parchment speckle so the land does not look like flat plastic.
  let seed = 11;
  const rand = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296);
  g.globalAlpha = theme.speckle;
  for (let i = 0; i < (w * h) / 90; i++) {
    g.fillStyle = rand() < 0.5 ? '#000' : '#fff';
    g.fillRect(rand() * w, rand() * h, 1.5, 1.5);
  }
  g.globalAlpha = 1;
}

// The regional map used by the journey scene.
export const MAP = { lon0: -10, lon1: 80, lat0: 24, lat1: 53, k: 0.3, cos: Math.cos((38.5 * Math.PI) / 180) };
MAP.width = (MAP.lon1 - MAP.lon0) * MAP.cos * MAP.k;
MAP.height = (MAP.lat1 - MAP.lat0) * MAP.k;

export function mapPosition(name, y = 0) {
  const [lon, lat] = PLACES[name] ?? PLACES['Багдад'];
  return new THREE.Vector3(
    (lon - MAP.lon0) * MAP.cos * MAP.k - MAP.width / 2,
    y,
    -((lat - MAP.lat0) * MAP.k - MAP.height / 2),
  );
}

let mapTex;
export function mapTexture() {
  if (mapTex) return mapTex;
  const w = 2048;
  const h = Math.round((w * MAP.height) / MAP.width);
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const g = canvas.getContext('2d');
  const project = (lon, lat) => [((lon - MAP.lon0) / (MAP.lon1 - MAP.lon0)) * w, (1 - (lat - MAP.lat0) / (MAP.lat1 - MAP.lat0)) * h];
  paint(g, w, h, project, {
    sea: '#1d4651', shallow: '#2a5c66', shallowWidth: 14, land: '#d9c49b', coast: '#8a6f45', coastWidth: 2.5,
    river: '#3f7d86', riverWidth: 3, speckle: 0.06,
  });
  // Graticule every 10°.
  g.strokeStyle = 'rgba(80,60,30,0.18)';
  g.lineWidth = 1.5;
  for (let lon = 0; lon <= 80; lon += 10) {
    const [x] = project(lon, 0);
    g.beginPath();
    g.moveTo(x, 0);
    g.lineTo(x, h);
    g.stroke();
  }
  for (let lat = 30; lat <= 50; lat += 10) {
    const [, y] = project(0, lat);
    g.beginPath();
    g.moveTo(0, y);
    g.lineTo(w, y);
    g.stroke();
  }
  mapTex = new THREE.CanvasTexture(canvas);
  mapTex.colorSpace = THREE.SRGBColorSpace;
  mapTex.anisotropy = 8;
  mapTex.userData.shared = true;
  return mapTex;
}

let worldTex;
export function worldTexture() {
  if (worldTex) return worldTex;
  const w = 2048;
  const h = 1024;
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const g = canvas.getContext('2d');
  const project = (lon, lat) => [((lon + 180) / 360) * w, ((90 - lat) / 180) * h];
  paint(g, w, h, project, {
    sea: '#163a4c', shallow: '#1f4d5f', shallowWidth: 8, land: '#cdb88c', coast: '#7c6640', coastWidth: 1.5,
    river: null, speckle: 0.05,
  });
  g.strokeStyle = 'rgba(255,255,255,0.08)';
  g.lineWidth = 1;
  for (let lon = -180; lon <= 180; lon += 30) {
    const [x] = project(lon, 0);
    g.beginPath();
    g.moveTo(x, 0);
    g.lineTo(x, h);
    g.stroke();
  }
  for (let lat = -60; lat <= 60; lat += 30) {
    const [, y] = project(0, lat);
    g.beginPath();
    g.moveTo(0, y);
    g.lineTo(w, y);
    g.stroke();
  }
  worldTex = new THREE.CanvasTexture(canvas);
  worldTex.colorSpace = THREE.SRGBColorSpace;
  worldTex.userData.shared = true;
  return worldTex;
}

// Same formula as THREE.SphereGeometry uses for its UVs.
export function spherePosition(lon, lat, radius) {
  const phi = ((lon + 180) / 360) * Math.PI * 2;
  const theta = ((90 - lat) / 180) * Math.PI;
  return new THREE.Vector3(
    -radius * Math.cos(phi) * Math.sin(theta),
    radius * Math.cos(theta),
    radius * Math.sin(phi) * Math.sin(theta),
  );
}
